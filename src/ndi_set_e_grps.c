/* See Knuth V2 pg. 234 */
static int doublecmp(double a, double b)
{
     double diff;
     double delta;

     diff = a - b;
     delta = (DBL_EPSILON + FLT_EPSILON * 
              (fabs(a) > fabs(b) ? fabs(a): fabs(b)));

     if (diff > delta) {         /* a > b */
          return +1;
     } else if (diff < -delta) { /* a < b */
          return -1;
     } else {                   /* a ~ b */
          return 0;
     }
}

