static int is_default_str(const char *grp_struct) {

    int return_val = 0;
    int char_count = 0;
    int int_flag = 0;
    const char *int_p = NULL;
    const char *curr_char = grp_struct;

    while (( char_count < strlen(grp_struct)) &&
           (*curr_char == ' ')) {
        curr_char++;
        char_count++;
    }
    while (( char_count < strlen(grp_struct)) &&
           (isdigit(*curr_char))) {
        if (! int_flag) {
            int_p = curr_char;
            int_flag = 1;
        }
        curr_char++;
        char_count++;
    }
    if ( int_flag &&
         (strcmp("_default", curr_char) == 0)) {
        return_val = strtol(int_p, (char **)NULL, 10);
    }
    
    return(return_val);
}

