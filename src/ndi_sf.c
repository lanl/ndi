#define NUM_SF (sizeof sf_data/sizeof sf_data[0])

/* binary search: see "The C Programming Language" p. 137 */
spont_fiss *ndi_get_sf_data(const char *zaid)
{
    long za;
    spont_fiss *low = &sf_data[0];
    spont_fiss *high = &sf_data[NUM_SF];
    spont_fiss *mid = NULL;
    long cond;

    za = atol(zaid);

    while (low < high) {
        mid = low + (high - low)/2;
        if ((cond = za - mid->za) < 0)
            high = mid;
        else if (cond > 0)
            low = mid + 1;
        else 
            return mid;
    }
    return NULL;
}

